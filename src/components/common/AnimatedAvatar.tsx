interface Props {
  className?: string;
  size?: number;
}

export function AnimatedAvatar({ className = "h-8 w-8", size = 32 }: Props) {
  const maskId = useId().replace(/:/g, "-") + "-mascot-mask";

  const [index, setIndex] = useState(() => {
    const saved = localStorage.getItem("recdesk_mascot_index");
    if (saved !== null) {
      const parsed = parseInt(saved, 10);
      if (!isNaN(parsed) && parsed >= 0 && parsed < MASCOTS.length) {
        return parsed;
      }
    }
    return 0; // Default to Excited Squircle
  });

  useEffect(() => {
    localStorage.setItem("recdesk_mascot_index", index.toString());
  }, [index]);

  const current = MASCOTS[index];

  const handleNext = () => {
    setIndex((prev) => (prev + 1) % MASCOTS.length);
  };

  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <button
          type="button"
          onClick={handleNext}
          data-tauri-drag-region={false}
          className={`group relative flex items-center justify-center rounded-lg p-0.5 transition-transform duration-150 hover:scale-110 active:scale-95 focus:outline-none cursor-pointer ${className}`}
          style={{ width: size, height: size }}
          aria-label={`RecDesk Mascot: ${current.name} (Click to switch)`}
        >
          <svg
            key={current.id}
            width={size}
            height={size}
            viewBox="-125 -125 250 250"
            role="img"
            aria-label={`Animated mascot: ${current.name}`}
            xmlns="http://www.w3.org/2000/svg"
            className="h-full w-full drop-shadow-xs transition-colors duration-300"
          >
            <defs>
              <mask
                id={maskId}
                maskUnits="userSpaceOnUse"
                x="-158"
                y="-158"
                width="316"
                height="316"
              >
                {/* Silhouette (White = visible) */}
                <path d={current.bodyPath} fill="#ffffff" />
                {/* Left eye cutout in mask */}
                <path
                  d={current.leftEyePath}
                  className="mascot-eye-0"
                  opacity="1"
                  fill="#000000"
                />
                {/* Right eye cutout in mask */}
                <path
                  d={current.rightEyePath}
                  className="mascot-eye-1"
                  opacity="1"
                  fill="#000000"
                />
              </mask>
            </defs>

            {/* Background layer (shows through eye cutouts as white eyeballs) */}
            <path d={current.bodyPath} fill="#ffffff" />

            {/* Dynamic Body Fill - automatically matches active theme primary color */}
            <g mask={`url(#${maskId})`}>
              <rect
                x="-158"
                y="-158"
                width="316"
                height="316"
                className="fill-primary transition-colors duration-300"
              />
            </g>

            {/* Scoped CSS Keyframe Animations */}
            <style>{`
              .mascot-eye-0, .mascot-eye-1 {
                transform-box: view-box;
                transform-origin: 0 0;
                animation-duration: 2.967s;
                animation-iteration-count: infinite;
                animation-timing-function: linear;
                animation-direction: alternate;
              }
              ${current.style}
            `}</style>
          </svg>
        </button>
      </TooltipTrigger>
      <TooltipContent>Mascot: {current.name} · Click to switch mood</TooltipContent>
    </Tooltip>
  );
}
